-- SOLO para una demostración aislada con datos ficticios.
-- Estas políticas permiten que cualquier visitante con la clave pública lea y modifique tickets.
-- No uses este esquema abierto con datos personales ni en producción.

create table if not exists public.tickets (
  id bigint generated by default as identity primary key,
  room_code text not null,
  category text not null,
  description text not null,
  teacher_name text not null,
  teacher_rut text not null,
  status text not null default 'open'
    check (status in ('open', 'escalated', 'accepted', 'rejected')),
  escalation_notes text not null default '',
  created_at timestamptz not null default now()
);

alter table public.tickets enable row level security;

grant select, insert, update on public.tickets to anon;
grant usage, select on sequence public.tickets_id_seq to anon;

drop policy if exists "demo anon select tickets" on public.tickets;
drop policy if exists "demo anon insert tickets" on public.tickets;
drop policy if exists "demo anon update tickets" on public.tickets;

create policy "demo anon select tickets" on public.tickets
  for select to anon using (true);
create policy "demo anon insert tickets" on public.tickets
  for insert to anon with check (true);
create policy "demo anon update tickets" on public.tickets
  for update to anon using (true) with check (true);

-- Añade la tabla a Realtime solo si aún no está en la publicación.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'tickets'
  ) then
    alter publication supabase_realtime add table public.tickets;
  end if;
end $$;
